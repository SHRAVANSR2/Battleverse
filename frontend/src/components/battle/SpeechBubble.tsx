import type { Verse } from "../../types/api";
import { paletteFor, RobotAvatar, variantForName } from "../character/RobotAvatar";
import { Chip } from "../ui/Chip";
import { VerseAudioControls } from "../audio/VerseAudioControls";

export interface SpeechBubbleProps {
  verse: Verse;
  side: "left" | "right";
  speaking: boolean;
  onPlay: (verseId: string) => void;
  pending?: boolean;
  error?: string | null;
}

export function SpeechBubble({
  verse,
  side,
  speaking,
  onPlay,
  pending = false,
  error = null,
}: SpeechBubbleProps) {
  const palette = paletteFor(verse.accent);
  const lines = verse.verse_text.split("\n").filter((line) => line.trim() !== "");
  const right = side === "right";

  return (
    <article
      className={`bv-bubble-row flex gap-3 ${right ? "flex-row-reverse" : ""}`}
      data-verse-id={verse.id}
      aria-label={`Verse ${verse.turn_number} by ${verse.character_name}`}
    >
      <div className="shrink-0 pt-6">
        <RobotAvatar
          accent={verse.accent}
          variant={variantForName(verse.character_name)}
          size={52}
          mood={speaking ? "speaking" : "idle"}
        />
      </div>

      <div className={`min-w-0 max-w-[92%] flex-1 sm:max-w-[82%] ${right ? "flex flex-col items-end" : ""}`}>
        <div
          className={`mb-1 flex flex-wrap items-center gap-2 text-xs text-slate-300 ${
            right ? "justify-end" : ""
          }`}
        >
          <span className="font-extrabold tracking-wide" style={{ color: palette.glow }}>
            {verse.character_name}
          </span>
          <span className="opacity-70">Round {verse.round_number}</span>
          {verse.is_demo ? (
            <Chip tone="demo" title="Demo Mode — scripted line, not AI-generated">
              demo
            </Chip>
          ) : verse.provider === "groq" || verse.provider === "gemini" ? (
            <Chip tone="accent" title={`Generated by ${verse.provider}`}>
              {verse.provider}
            </Chip>
          ) : null}
          {speaking ? (
            <span
              className="inline-flex items-center gap-1.5 font-semibold"
              style={{ color: palette.glow }}
            >
              <span className="bv-wave" aria-hidden="true">
                <span />
                <span />
                <span />
                <span />
              </span>
              Speaking
            </span>
          ) : null}
        </div>

        <div
          className={`bv-bubble bv-transition ${right ? "bv-bubble-right" : "bv-bubble-left"} ${
            speaking ? "bv-bubble-live" : ""
          }`}
          style={{
            ["--accent" as string]: palette.body,
            ["--accent-soft" as string]: palette.glow,
          }}
        >
          <p className="m-0">
            {lines.map((line, index) => (
              <span
                key={index}
                className={`bv-line ${index === lines.length - 1 ? "bv-line-punch" : ""}`}
                style={{ animationDelay: `${index * 160}ms` }}
              >
                {line}
              </span>
            ))}
          </p>

          <div className={`mt-2 flex items-center gap-2 ${right ? "justify-end" : ""}`}>
            <VerseAudioControls
              verseId={verse.id}
              accent={palette.body}
              speaking={speaking}
              pending={pending}
              error={error}
              onPlay={onPlay}
              hasAudio={Boolean(verse.audio)}
            />
          </div>
        </div>
      </div>
    </article>
  );
}